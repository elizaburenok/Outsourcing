/**
 * Маршруты прототипа.
 * Навигация внутри ОБ строится от контента Главной (вкладки), поэтому
 * верхнего уровня маршрутов немного — ОБ живёт на одной Главной.
 */
export const ROUTES = {
  home: '/home',
  history: '/history',
  /** Отчётность — отчёты и декларации под контролем бухгалтера. */
  reports: '/reports',
  /** Чат с бухгалтером — канал этапа 1 онбординга нового ЛК. */
  chat: '/chat',
  /** Страница уплаты конкретного налога/платежа. */
  pay: '/pay/:id',
} as const

/** Путь к странице уплаты для конкретного платежа. */
export function payTo(id: string): string {
  return `/pay/${id}`
}
