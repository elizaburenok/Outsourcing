/** Денежный формат ₽ с неразрывными пробелами между разрядами. */
export function formatMoney(value: number): string {
  return value.toLocaleString('ru-RU').replace(/\s/g, ' ') + ' ₽'
}

/**
 * «Короткие» служебные слова, которые по правилам русской типографики нельзя оставлять
 * висеть в конце строки: предлоги, союзы, частицы и любые одно-/двухбуквенные слова.
 * После них ставим неразрывный пробел, чтобы они переносились вместе со следующим словом.
 */
const SHORT_WORDS =
  /(^|[\s(])([А-Яа-яЁё]{1,2}|для|под|над|при|без|про|изо|обо|ото|или|как|что|это|уже|там|чем)[ \t\n](?=\S)/gi

export function nbsp(text: string): string {
  // Два прохода — чтобы «склеить» цепочки коротких слов подряд («на… и… по…»),
  // где пробел-разделитель уже поглотили предыдущим совпадением.
  let out = text
  for (let i = 0; i < 2; i++) {
    out = out.replace(SHORT_WORDS, (_m, pre: string, word: string) => `${pre}${word} `)
  }
  return out
}
